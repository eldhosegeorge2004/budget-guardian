import datetime
from fastapi.testclient import TestClient
from backend.main import app
from backend.agent.brain import run_agent_cycle

def main():
    client = TestClient(app)

    print("==================================================")
    print(" [TEST] BUDGET GUARDIAN - LIVE DEMO SYNC TEST")
    print("==================================================")

    # 1. Check pre-sync status
    summary_before = client.get("/transactions/summary").json()
    print("\n[1] PRE-SYNC STATS:")
    print(f"    - Total Transactions : {summary_before.get('total_transactions')}")
    print(f"    - Total Outflow      : ${summary_before.get('total_outflow', 0):,.2f}")
    print(f"    - Unread Alerts      : {summary_before.get('unread_alerts')}")

    # 2. Ingest a simulated high-value PayPal event
    print("\n[2] SIMULATING NEW PAYPAL EVENT...")
    sim_payload = {
        "merchant_name": "Anthropic PBC (AI API)",
        "amount": 750.00,
        "note": "Claude 3.7 Scale-Tier Automated Invoice",
        "category": "SaaS/Software"
    }
    res = client.post("/demo/simulate-transaction", json=sim_payload)
    tx_data = res.json()
    print(f"    - PayPal Transaction ID : {tx_data.get('transaction_id')}")
    print(f"    - Merchant              : {sim_payload['merchant_name']}")
    print(f"    - Amount Charged        : ${sim_payload['amount']:.2f}")

    # 3. Trigger Agent Evaluation Cycle
    print("\n[3] RUNNING AGENT BRAIN CYCLE (Anomaly + Policy Check)...")
    run_agent_cycle()

    # 4. Review Post-Sync Status
    summary_after = client.get("/transactions/summary").json()
    print("\n[4] POST-SYNC STATS:")
    print(f"    - Total Transactions : {summary_after.get('total_transactions')} (+1)")
    print(f"    - Total Outflow      : ${summary_after.get('total_outflow', 0):,.2f}")
    print(f"    - Unread Alerts      : {summary_after.get('unread_alerts')}")

    # 5. Inspect the generated alert
    alerts = client.get("/alerts").json()
    if alerts:
        latest = alerts[0]
        print("\n[5] [ALERT] NEW ALERT GENERATED BY AGENT:")
        print(f"    - Message     : {latest.get('message')}")
        print(f"    - Severity    : {latest.get('severity')}")
        print(f"    - Explanation : {latest.get('ai_explanation')}")
        print(f"    - Action Plan : {latest.get('recommended_action')}")
    print("\n==================================================")
    print(" [SUCCESS] DEMO SYNC TEST COMPLETED SUCCESSFULLY!")
    print("==================================================")

if __name__ == "__main__":
    main()
